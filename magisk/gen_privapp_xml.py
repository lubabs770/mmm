#!/usr/bin/env python3
"""Generates the priv-app permission allowlist from the app manifest.

On Android 9 and later, with ``ro.control_privapp_permissions=enforce``, a
privileged app that requests a privileged permission *without* being allowlisted
can stop the phone from booting. So the list is generated from the manifest in CI
rather than maintained by hand: the two cannot drift apart.

The manifest marks the privileged block with comments::

    <!-- privileged: … -->
    <uses-permission android:name="android.permission.MODIFY_PHONE_STATE" … />
    <!-- /privileged -->

Usage:
    gen_privapp_xml.py <AndroidManifest.xml> [output.xml]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PACKAGE = "lubabs770.mmm.modemizer"
BEGIN = "<!-- privileged"
END = "<!-- /privileged -->"
PERMISSION = re.compile(r'android:name="([A-Za-z0-9_.]+)"')


class MarkerError(RuntimeError):
    pass


def privileged_permissions(manifest: str) -> list[str]:
    start = manifest.find(BEGIN)
    if start < 0:
        raise MarkerError(f"no {BEGIN!r} marker in the manifest")
    end = manifest.find(END, start)
    if end < 0:
        raise MarkerError(f"no {END!r} marker after {BEGIN!r}")
    block = manifest[start:end]
    found = [name for name in PERMISSION.findall(block) if name.startswith("android.permission.")]
    if not found:
        raise MarkerError("the privileged block lists no permissions")
    # Keep manifest order, drop duplicates.
    seen: list[str] = []
    for name in found:
        if name not in seen:
            seen.append(name)
    return seen


def render(permissions: list[str], package: str = PACKAGE) -> str:
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by magisk/gen_privapp_xml.py from app/src/main/AndroidManifest.xml. -->",
        "<permissions>",
        f'    <privapp-permissions package="{package}">',
    ]
    lines += [f'        <permission name="{name}"/>' for name in permissions]
    lines += ["    </privapp-permissions>", "</permissions>", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    manifest = Path(argv[0]).read_text(encoding="utf-8")
    xml = render(privileged_permissions(manifest))
    if len(argv) > 1:
        Path(argv[1]).write_text(xml, encoding="utf-8")
        print(f"wrote {argv[1]}")
    else:
        sys.stdout.write(xml)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
